// Command genassets vendors the heraldry renderer's artwork and writes its
// library table. It reads the library from kbeads' source
// (kbeads/internal/heraldry, through kbeadssrc), copies each charge's 128 px
// PNG from a checkout of googlefonts/noto-emoji at the library's pinned tag
// into assets/ and its 72 px PNG into assets/72/, removes any asset the
// library no longer holds, vendors the upstream LICENSE, and writes
// library_gen.go.
//
// Run from gardenio/controller/internal/heraldry:
//
//	git clone --depth 1 --branch <NotoEmojiTag> --filter=blob:none --sparse \
//	  https://github.com/googlefonts/noto-emoji.git /tmp/noto
//	git -C /tmp/noto sparse-checkout set 2D/png/128 2D/png/72
//	GOWORK=off go run ./genassets -noto /tmp/noto
//
// (GOWORK=off is not needed from inside the workspace; it is harmless.)
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"image/png"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"gardenio/controller/internal/heraldry/kbeadssrc"
)

// sizes are the artwork sizes the renderer embeds, each in its directory
// (spec §6.4): 128 px, the default, and 72 px for SVGOptions.Small (a 24 px
// slot at 3×). Noto ships 72, 128 and 512.
var sizes = []struct {
	px  int
	dir string
}{{128, "assets"}, {72, filepath.Join("assets", "72")}}

func main() {
	noto := flag.String("noto", "", "checkout of googlefonts/noto-emoji at the library's pinned tag")
	kbeads := flag.String("kbeads", "../../../../kbeads/internal/heraldry", "kbeads' heraldry package directory")
	flag.Parse()
	if *noto == "" {
		log.Fatal("genassets: -noto DIR is required")
	}
	src, err := kbeadssrc.Read(*kbeads)
	if err != nil {
		log.Fatal(err)
	}
	if tag := checkoutTag(*noto); tag != "" && tag != src.NotoEmojiTag {
		log.Fatalf("genassets: %s is at %s, the library pins %s", *noto, tag, src.NotoEmojiTag)
	}

	for _, sz := range sizes {
		if err := os.MkdirAll(sz.dir, 0o755); err != nil {
			log.Fatal(err)
		}
		keep := map[string]bool{"LICENSE": true, "README.md": true, "72": true}
		for _, c := range src.Library {
			name := "emoji_u" + c.Codepoints + ".png"
			b, err := os.ReadFile(filepath.Join(*noto, "2D", "png", fmt.Sprint(sz.px), name))
			if err != nil {
				log.Fatalf("genassets: %s (%s) has no %d px artwork: %v", c.Emoji, c.Name, sz.px, err)
			}
			cfg, err := png.DecodeConfig(bytes.NewReader(b))
			if err != nil || cfg.Width != sz.px || cfg.Height != sz.px {
				log.Fatalf("genassets: %s is not a %d px PNG (%v)", name, sz.px, err)
			}
			if err := writeIfChanged(filepath.Join(sz.dir, name), b); err != nil {
				log.Fatal(err)
			}
			keep[name] = true
		}
		ents, err := os.ReadDir(sz.dir)
		if err != nil {
			log.Fatal(err)
		}
		for _, e := range ents {
			if !keep[e.Name()] {
				if err := os.Remove(filepath.Join(sz.dir, e.Name())); err != nil {
					log.Fatal(err)
				}
			}
		}
	}
	lic, err := os.ReadFile(filepath.Join(*noto, "LICENSE"))
	if err != nil {
		log.Fatal(err)
	}
	if err := writeIfChanged(filepath.Join("assets", "LICENSE"), lic); err != nil {
		log.Fatal(err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by genassets from kbeads/internal/heraldry; DO NOT EDIT.\n")
	b.WriteString("// Regenerate with `go run ./genassets -noto DIR` (see genassets).\n\n")
	b.WriteString("package heraldry\n\n")
	fmt.Fprintf(&b, "// NotoEmojiTag is the googlefonts/noto-emoji release the assets are drawn from.\nconst NotoEmojiTag = %q\n\n", src.NotoEmojiTag)
	b.WriteString("// library is every charge, in Unicode emoji order; each has assets/emoji_u<Codepoints>.png and assets/72/emoji_u<Codepoints>.png.\nvar library = []Charge{\n")
	for _, c := range src.Library {
		fmt.Fprintf(&b, "\t{Emoji: %q, Name: %q, Codepoints: %q},\n", c.Emoji, c.Name, c.Codepoints)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := writeIfChanged("library_gen.go", out); err != nil {
		log.Fatal(err)
	}
	log.Printf("genassets: %d charges, Noto %s", len(src.Library), src.NotoEmojiTag)
}

// checkoutTag is the tag the Noto checkout sits on, "" if git cannot say.
func checkoutTag(dir string) string {
	out, err := exec.Command("git", "-C", dir, "describe", "--tags", "--exact-match").Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}

func writeIfChanged(path string, b []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, b) {
		return nil
	}
	return os.WriteFile(path, b, 0o644)
}
