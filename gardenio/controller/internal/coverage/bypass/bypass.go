// Package bypass parses Coverage-Bypass trailers from MR commit messages
// and emits a Bypass record consumed by the coverage gate (W2b-1), the bot
// comment (W2b-3), and the coverage status check (W2b-2).
//
// Spec: docs/research/coverage-phase2b-design.md §7.
//
// Trailer syntax:
//
//	Coverage-Bypass: <reason>
//
// where <reason> is exactly one of refactor, emergency, tooling-broken,
// generated. Anything else (unknown reason, empty value, scope qualifiers
// like `component=...`) is a parse error. The caller MUST treat a parse
// error as "no bypass granted" — the gate evaluates normally and fails
// closed if coverage is below threshold. We never silently allow.
//
// Per-component bypass scope is explicitly rejected as a footgun: a
// reviewer who lets `Coverage-Bypass: emergency component=coop` through
// has approved an emergency *for the whole PR*, not just one component.
// Per §7, bypass is whole-PR only.
//
// Multi-commit semantics: trailers from later commits win (matches
// `git interpret-trailers` last-trailer semantics and squash-merge
// concatenation order). Invalid trailers in earlier commits are
// reported via UnknownReasons so the caller can surface them in the
// bot comment.
package bypass

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
	"time"
)

// Reason is the validated bypass reason.
type Reason string

const (
	ReasonRefactor      Reason = "refactor"
	ReasonEmergency     Reason = "emergency"
	ReasonToolingBroken Reason = "tooling-broken"
	ReasonGenerated     Reason = "generated"
)

// AllReasons returns the canonical list of valid reasons in spec order.
func AllReasons() []Reason {
	return []Reason{ReasonRefactor, ReasonEmergency, ReasonToolingBroken, ReasonGenerated}
}

// Valid reports whether r is one of the named reasons.
func (r Reason) Valid() bool {
	switch r {
	case ReasonRefactor, ReasonEmergency, ReasonToolingBroken, ReasonGenerated:
		return true
	}
	return false
}

// FollowUp returns the follow-up bead obligation that this reason carries
// per §7.3. The obligation drives bot comment text, auto-bead creation,
// and pre-merge enforcement (tooling-broken).
func (r Reason) FollowUp() FollowUp {
	switch r {
	case ReasonRefactor:
		return FollowUp{
			Reason:                r,
			BlastRadius:           "patch-cov skipped; gate passes",
			BeadKind:              "bug",
			BeadLabels:            []string{"coverage", "coverage-bypass"},
			BeadSubjectFmt:        "coverage:refactor bypass on MR !%d",
			AutoCloseOnNoMainDrop: true,
		}
	case ReasonGenerated:
		return FollowUp{
			Reason:                r,
			BlastRadius:           "patch-cov advisory",
			BeadKind:              "bug",
			BeadLabels:            []string{"coverage", "coverage-bypass"},
			BeadSubjectFmt:        "coverage:generated bypass on MR !%d",
			AutoCloseOnNoMainDrop: true,
		}
	case ReasonEmergency:
		return FollowUp{
			Reason:           r,
			BlastRadius:      "all gates skipped",
			BeadKind:         "bug",
			BeadLabels:       []string{"coverage", "coverage-bypass", "emergency"},
			BeadSubjectFmt:   "coverage:emergency bypass on MR !%d — file the gap test",
			RequireWithin:    24 * time.Hour,
			ReminderAfter:    7 * 24 * time.Hour,
			SquawkOpsChannel: true,
		}
	case ReasonToolingBroken:
		return FollowUp{
			Reason:             r,
			BlastRadius:        "all gates skipped",
			BeadKind:           "bug",
			BeadLabels:         []string{"coverage", "coverage-bypass", "tooling-broken"},
			BeadSubjectFmt:     "coverage:tooling-broken bypass on MR !%d",
			RequiredPreMerge:   true,
			BlockCommentOnMiss: true,
		}
	}
	return FollowUp{Reason: r}
}

// FollowUp captures the §7.3 obligation row for a reason. Consumers
// (W2b-3 bot, W2b-2 status check) read these fields rather than
// re-deriving them from the reason string — the §7.3 table is
// authoritative and lives here so a reviewer can spot drift in one
// place.
type FollowUp struct {
	Reason      Reason
	BlastRadius string

	// Bead shape for the auto-filed follow-up.
	BeadKind       string
	BeadLabels     []string
	BeadSubjectFmt string // %d is the MR iid

	// AutoCloseOnNoMainDrop: refactor + generated. The follow-up
	// bead is auto-closed when the next main-push coverage shows no
	// drop (W2b-3 reconciliation).
	AutoCloseOnNoMainDrop bool

	// RequiredPreMerge: tooling-broken. The bot must fail the
	// comment job (BlockCommentOnMiss) until a matching bug bead
	// exists before the MR is merged.
	RequiredPreMerge   bool
	BlockCommentOnMiss bool

	// RequireWithin / ReminderAfter / SquawkOpsChannel: emergency.
	// Bead is filed at MR-merge time; reminder fires if it stays
	// open longer than ReminderAfter; ops squawk fires immediately.
	RequireWithin    time.Duration
	ReminderAfter    time.Duration
	SquawkOpsChannel bool
}

// Commit is the minimal commit shape Parse needs. Callers project
// from their MR-source struct (GitLab API, git-log JSON, …).
type Commit struct {
	SHA     string
	Author  string // "Name <email>" or just name; opaque to the parser
	Message string // full commit message including subject + body
}

// Bypass is the parsed result. CommitSHA / Author / RawTrailer
// identify *which* commit carried the active trailer (the last one
// per last-write-wins). Reason is always Valid().
type Bypass struct {
	Reason     Reason
	Author     string
	CommitSHA  string
	RawTrailer string // verbatim trailer text e.g. "Coverage-Bypass: emergency"
	FollowUp   FollowUp

	// UnknownReasons lists invalid trailer values seen in *other*
	// commits in the same MR. The bot surfaces these as
	// "ignored unknown bypass reason: <text>" warnings.
	UnknownReasons []string
}

// Sentinel errors. Callers should treat any non-nil error from Parse
// as "no bypass granted; gate evaluates normally". The caller is
// responsible for logging a warning and surfacing the unknown reason
// in the bot comment per §7.1.
var (
	// ErrUnknownReason: the active trailer's value is not one of
	// the four named reasons.
	ErrUnknownReason = errors.New("coverage-bypass: unknown reason")
	// ErrPerComponentScope: the trailer carries scope qualifiers
	// (component=…, scope=…, etc.). Per-component bypass is
	// explicitly rejected as a footgun (§7).
	ErrPerComponentScope = errors.New("coverage-bypass: per-component scope is not supported; bypass is whole-PR only")
	// ErrEmptyReason: the trailer key is present with no value.
	ErrEmptyReason = errors.New("coverage-bypass: empty reason")
)

// trailerLine matches `Coverage-Bypass: <value>` at the start of a line
// (with optional leading whitespace after squash-merge concatenation).
// Case-insensitive on the key.
var trailerLine = regexp.MustCompile(`(?im)^[ \t]*coverage-bypass[ \t]*:[ \t]*(.*?)[ \t]*$`)

// Parse walks commits in input order and returns the active Bypass,
// applying last-write-wins. Returns (nil, nil) when no commit carries
// a Coverage-Bypass trailer.
//
// On error, the returned *Bypass is nil. The caller MUST treat this
// as "no bypass granted" and let the gate evaluate normally — failing
// closed if coverage is below threshold. Never silently allow.
func Parse(commits []Commit) (*Bypass, error) {
	type hit struct {
		commit Commit
		raw    string
		value  string
	}
	var hits []hit
	for _, c := range commits {
		for _, m := range trailerLine.FindAllStringSubmatch(c.Message, -1) {
			// m[0] is the full matched line, m[1] is the captured value.
			raw := strings.TrimSpace(m[0])
			val := strings.TrimSpace(m[1])
			hits = append(hits, hit{commit: c, raw: raw, value: val})
		}
	}
	if len(hits) == 0 {
		return nil, nil
	}

	// Last-write-wins: the last hit is the active trailer.
	active := hits[len(hits)-1]

	// Collect unknown values from non-active hits (warnings).
	var unknowns []string
	for i, h := range hits {
		if i == len(hits)-1 {
			continue
		}
		// We only surface non-active values that are *also* invalid;
		// a valid earlier value that was overridden by a later valid
		// one is not noise worth surfacing.
		if _, err := validateValue(h.value); err != nil {
			unknowns = append(unknowns, h.value)
		}
	}

	reason, err := validateValue(active.value)
	if err != nil {
		return nil, fmt.Errorf("commit %s: %w (got %q)", short(active.commit.SHA), err, active.value)
	}

	return &Bypass{
		Reason:         reason,
		Author:         active.commit.Author,
		CommitSHA:      active.commit.SHA,
		RawTrailer:     active.raw,
		FollowUp:       reason.FollowUp(),
		UnknownReasons: unknowns,
	}, nil
}

// validateValue checks a trailer value and returns the named Reason
// or a sentinel error. Splits on whitespace to detect per-component
// scope qualifiers.
func validateValue(v string) (Reason, error) {
	if v == "" {
		return "", ErrEmptyReason
	}
	// Reject any qualifier syntax: `emergency component=coop`,
	// `emergency scope=controller`, `emergency, component=coop`,
	// `emergency; foo`. Whole-PR bypass is one bare token.
	for _, ch := range v {
		switch ch {
		case ' ', '\t', ',', ';', '=', '(', ')', '/', '*':
			return "", ErrPerComponentScope
		}
	}
	r := Reason(strings.ToLower(v))
	if !r.Valid() {
		return "", ErrUnknownReason
	}
	return r, nil
}

func short(sha string) string {
	if len(sha) > 8 {
		return sha[:8]
	}
	return sha
}
