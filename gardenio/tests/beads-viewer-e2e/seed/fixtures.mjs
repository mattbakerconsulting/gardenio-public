// gd-2grxUwFub7 helper: build a minimal widget-type bead per slug used by
// the widget-instance fixtures below. The kbeads pre-write validator
// (kbeads/internal/server/widget_validation.go::validateWidgetInstanceFields)
// rejects widget-instance writes whose `widget_type` does not resolve to a
// widget-type bead with a matching `slug`. The Go-coded ("builtin") widgets
// rendered by the beads-viewer are not auto-registered as widget-type beads
// at daemon startup, so the e2e seed must create one stub per slug. Stubs
// are renderer_kind=builtin with no `schema` — the validator's schema branch
// no-ops (line 150) and the rendering path in widget_types.go falls back to
// the Go-coded renderer by slug. Tests assert on rendered widget-instance
// cards, not on the type beads.
function widgetTypeStub(slug) {
  return {
    key: `widget_type_${slug.replace(/-/g, '_')}`,
    type: 'widget-type',
    title: `[E2E fixture] widget-type ${slug}`,
    description: `Stub widget-type bead so widget-instance writes with widget_type=${slug} pass kbeads pre-write validation.`,
    fields: [
      ['slug', slug],
      ['renderer_kind', 'builtin'],
    ],
  };
}

// ka-0000003679 helper: build a widget-instance fixture that renders as a
// child of the rich_report fixture. Each widget kind needs the same shape
// (parent(__rich_report__) typed mention + standard widget-instance fields)
// so a thin builder keeps the FIXTURES table readable.
function widgetInstance({ key, widgetType, position, headline, data, summary }) {
  const note = summary || `${widgetType} fixture for the rich-report widget child render path.`;
  return {
    key,
    type: 'widget-instance',
    title: `[E2E fixture] widget ${widgetType}`,
    description: `${note}\n\nparent(__rich_report__)\n`,
    fields: [
      ['widget_type', widgetType],
      ['position', String(position)],
      ['headline', headline],
      ['data', JSON.stringify(data)],
    ],
    typedMentionPlaceholders: [
      { token: '__rich_report__', fixtureKey: 'rich_report' },
    ],
  };
}

// gd-DkG9VPzBgX helper: build one closed iteration-agent fixture in a
// gardener's life-thread. Each iteration is a type=agent bead stamped with the
// gardener wiring stampGardenerLoopContext writes on real runs:
//
//   schedule_id              → resolved to the gardener fixture's id post-seed
//                              (the daemon-indexed FK gardenerIterations filters on)
//   schedule_prior_agent_id  → resolved to the PREVIOUS iteration fixture's id,
//                              so the chain orders root-forward 1..N without the
//                              created_at fallback ("by time") kicking in
//   schedule_max_runs        → drives the "of N" run-label suffix
//   schedule_terminal_goal   → per-run goal snapshot
//
// Every iteration is CLOSED (closeAfterSeed) and carries a `wrapup` JSON so the
// iteration card renders an OUTCOME headline (tldr) instead of the bare agent
// name — the card template flags an outcome-less run with .gardener-iter-noutcome,
// which the spec asserts is absent. The wrapup's blockers field flips the
// per-run exit chip between "clean exit" (gardener-iter-exit-ok) and "blocked
// exit" (gardener-iter-exit-fail). `prior` is the fixture key of the preceding
// iteration (null for the first run).
function gardenerIteration({ key, runNumber, prior, wrapup }) {
  const fieldRefs = [{ field: 'schedule_id', fixtureKey: 'gardener' }];
  if (prior) {
    fieldRefs.push({ field: 'schedule_prior_agent_id', fixtureKey: prior });
  }
  return {
    key,
    type: 'agent',
    title: `[E2E fixture] gardener run ${runNumber}`,
    description: `Iteration ${runNumber} of the gardener-page life-thread fixture (gd-DkG9VPzBgX).`,
    role: 'crew',
    fields: [
      ['agent', `fixture-gardener-run-${runNumber}`],
      ['role', 'crew'],
      ['project', 'gardenio'],
      ['agent_state', 'done'],
      ['pod_phase', 'succeeded'],
      // schedule_max_runs / schedule_runs_spawned / wrapup are STRING-typed
      // fields on type:agent. `kd --field` auto-coerces a bare number or a
      // leading-`{` value to a JSON number/object, which the daemon rejects
      // for a string field — so we hand kd an already-JSON-quoted value
      // (rawOrString in kbeads/cmd/kd/fields.go keeps a leading-`"` valid-JSON
      // token as a string). The decoded field value is then the plain string
      // the viewer's parseWrapUpSummary / parseScheduleInt expect.
      ['schedule_max_runs', '"10"'],
      ['schedule_runs_spawned', JSON.stringify(String(runNumber))],
      ['schedule_terminal_goal', 'Drive the demo epic to merged + green.'],
      ['wrapup', JSON.stringify(JSON.stringify(wrapup))],
    ],
    // Resolved post-seed by resolveFieldRefs in seed.mjs — the referenced
    // fixture ids do not exist until the whole table is seeded.
    fieldRefs,
    // Iterations must be terminal so the card renders wrapup-derived outcomes
    // and exit chips (live runs carry no wrapup yet).
    closeAfterSeed: true,
  };
}

