// Canonical fixture spec for the beads-viewer behavioral E2E suite.
//
// Phase T2 (ka-0000006317) of epic ka-0000004611. The plan of record at
// `gardenio/plans/beads-viewer-playwright-tests.md` recommends a "seeded
// real daemon" strategy (vs. an in-process fake) because the wire
// protocol IS part of what the suite asserts. This file is the
// declarative description of *what* gets seeded; `seed.mjs` does the
// idempotent put.
//
// One bead per type touched by `templates/partials/type_*.html`. Tests
// reference fixtures by `key` (e.g. `fixtures.schedule.id`) — the actual
// `kd-...` id is auto-generated by the daemon and resolved at seed time
// into `fixtures/ids.json`. That manifest is what makes the ids stable
// across test runs against the same daemon: each fixture is identified
// by the `fixture:e2e:<key>` label, so subsequent seeds find and reuse
// the existing bead instead of creating a duplicate.
//
// Adding a fixture: append an entry below, re-run `make
// seed-beads-viewer-e2e`. Removing one: drop the entry; the existing
// bead is left in place for safety (delete by hand if needed).

