// Emits fixtures.check.ts: every golden fixture under ../fixtures/<Schema>/ as
// an object literal that must satisfy components["schemas"][<Schema>] from the
// generated binding. `npm run check` (tsc) then fails on a missing required
// field, a wrong enum value or an unknown field, so the one fixture set the Go
// tests validate also type-checks the TypeScript client. ../fixtures/_invalid
// is skipped: those must fail, and the Go tests prove they do.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../fixtures/", import.meta.url).pathname;
const lines = [
  "// Code generated by gen-fixture-check.mjs from ../fixtures. DO NOT EDIT.",
  'import type { components } from "./lands-v1";',
  "",
  'type S = components["schemas"];',
  "",
];

for (const schema of readdirSync(root).sort()) {
  if (schema === "_invalid" || !statSync(join(root, schema)).isDirectory()) continue;
  for (const file of readdirSync(join(root, schema)).sort()) {
    if (!file.endsWith(".json")) continue;
    const body = JSON.stringify(JSON.parse(readFileSync(join(root, schema, file), "utf8")), null, 2);
    const name = `${schema}_${file.slice(0, -".json".length)}`.replace(/[^A-Za-z0-9_]/g, "_");
    lines.push(`export const ${name} = ${body} satisfies S[${JSON.stringify(schema)}];`, "");
  }
}

writeFileSync(new URL("fixtures.check.ts", import.meta.url), lines.join("\n"));
