#!/usr/bin/env bash
# public-readiness-inventory.sh — count placeholder and dead-host references
# by pattern, by top-level directory, and by file class. Read-only. Output is
# markdown; the 2026-10-31 snapshot is archived at
# docs/archive/public-readiness-inventory.md (its pattern table names the
# banned strings, so a live copy would trip the public-strings guard).
#
# Usage: scripts/public-readiness-inventory.sh [ROOT] > docs/archive/public-readiness-inventory.md
set -euo pipefail

ROOT="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
cd "$ROOT"

EXCLUDES=(--exclude-dir=.worktrees --exclude-dir=node_modules --exclude-dir=vendor
          --exclude-dir=gen --exclude-dir=.git --exclude-dir=dist --exclude-dir=target)

PATTERNS=(
  'Acme'
  'acme\.example'
  'gitlab\.com/[Aa]cme'
  'registry\.gitlab\.com/[Aa]cme'
  'prod\.gardenio\.acme\.example'
  'cli\.gardenio\.acme\.example'
  'Acme/[P]latform'  # bracketed so this file does not match the strings guard
)
ANY='[Aa]cme|acme\.example|gitlab\.com/[Aa]cme|prod\.gardenio\.acme\.example|cli\.gardenio\.acme\.example'

echo "# Public-readiness inventory"
echo
echo "Generated by \`scripts/public-readiness-inventory.sh\` at commit $(git rev-parse --short HEAD) on $(date -u +%Y-%m-%d)."
echo
echo "## By pattern"
echo
# Markdown code-span delimiter, kept out of the printf format below.
bt='`'
echo "| Pattern | Files | Lines |"
echo "|---|---|---|"
for p in "${PATTERNS[@]}"; do
  # grep exits 1 on no match; a zero row is a valid answer, not a failure.
  files=$({ grep -rIlE "${EXCLUDES[@]}" -e "$p" . || true; } | wc -l)
  lines=$({ grep -rIE "${EXCLUDES[@]}" -e "$p" . || true; } | wc -l)
  printf '| %s%s%s | %s | %s |\n' "$bt" "$p" "$bt" "$files" "$lines"
done

matching=$(mktemp); trap 'rm -f "$matching"' EXIT
grep -rIlE "${EXCLUDES[@]}" -e "$ANY" . > "$matching" || true

echo
echo "## By top-level directory (files matching any pattern)"
echo
echo "| Directory | Files |"
echo "|---|---|"
awk -F/ '{print $2}' "$matching" | sort | uniq -c | sort -rn | awk '{printf "| `%s` | %s |\n", $2, $1}'

echo
echo "## By file class"
echo
echo "| Class | Files |"
echo "|---|---|"
python3 - "$matching" <<'PY'
import re, sys, collections
cls = collections.Counter()
for f in open(sys.argv[1]):
    f = f.strip()
    if re.search(r'_test\.go$|/tests?/|/e2e/|testdata|fixtures?/', f): c = 'tests / fixtures'
    elif re.search(r'(^|/)README\.md$', f): c = 'README'
    elif re.search(r'(^|/)docs/', f): c = 'docs'
    elif re.search(r'/helm/.*values.*\.ya?ml$|deploy-values/', f): c = 'chart values'
    elif re.search(r'/helm/.*/templates/', f): c = 'chart templates'
    elif f.endswith('.go'): c = 'Go source'
    elif f.endswith('.rs'): c = 'Rust source'
    elif f.endswith('.sh') or '/scripts/' in f: c = 'scripts'
    elif re.search(r'\.github/|\.captain/|Makefile', f): c = 'CI'
    elif f.endswith('.md'): c = 'other markdown'
    elif re.search(r'\.(ya?ml|json|toml)$', f): c = 'other config'
    else: c = 'other'
    cls[c] += 1
for k, v in cls.most_common():
    print(f'| {k} | {v} |')
PY

echo
echo "## Treatment"
echo
echo "Per the public-ready scrub plan (epic gd-uNpaF2zvVH; spec §0 D1): placeholders stay in tests and fixtures; only the user-facing surface (§2) is rewritten."
