package main

import (
	"bufio"
	"fmt"
	"image"
	"os"
	"strings"
	"sync"
)

func hexJoin(cps []rune, f, sep string) string {
	var s []string
	for _, r := range cps {
		s = append(s, fmt.Sprintf(f, r))
	}
	return strings.Join(s, sep)
}

func baseRunes(emoji string) []rune {
	var out []rune
	for _, r := range emoji {
		if r != 0xFE0F {
			out = append(out, r)
		}
	}
	return out
}

// cached wraps a Charges source so each PNG is decoded once (the library
// sheets render every charge many times).
type cached struct {
	src Charges
	mu  sync.Mutex
	m   map[string]image.Image
}

func cache(src Charges) *cached { return &cached{src: src, m: map[string]image.Image{}} }

func (c *cached) PNG72(emoji string) (image.Image, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if img, ok := c.m[emoji]; ok {
		return img, nil
	}
	img, err := c.src.PNG72(emoji)
	if err == nil {
		c.m[emoji] = img
	}
	return img, err
}

// Charge is one library row (gardenio/docs/heraldry/library.md, generated by
// kbeads' genlibrary): the emoji as stored and its plain-words name.
type Charge struct{ Emoji, Name string }

// LoadLibrary reads the charge table out of library.md, in its order.
func LoadLibrary(path string) ([]Charge, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []Charge
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		c := strings.Split(sc.Text(), "|")
		// | 🤪 | zany face | U+1F92A | Smileys & Emotion |
		if len(c) != 6 || !strings.HasPrefix(strings.TrimSpace(c[3]), "U+") {
			continue
		}
		out = append(out, Charge{strings.TrimSpace(c[1]), strings.TrimSpace(c[2])})
	}
	return out, sc.Err()
}

// nameOf is the library name of an emoji, VS16 or not.
func nameOf(lib []Charge) func(string) string {
	m := map[string]string{}
	for _, c := range lib {
		m[string(baseRunes(c.Emoji))] = c.Name
	}
	return func(e string) string {
		if n, ok := m[string(baseRunes(e))]; ok {
			return n
		}
		return "?" + hexJoin(baseRunes(e), "%x", "_")
	}
}
