package main

import (
	"fmt"
	"math"
	"strings"
)

// The standard shield (heraldry spec §6.2), in design units on its 64×72 grid.
// These constants are the drawing: shield.svg and shield-grid.svg under
// gardenio/docs/heraldry/ are generated from them (`go run . svg`), and the
// raster path below draws the same outline.
//
// A classical heater: a flat top, straight sides down to SideY, then two arcs
// of radius ArcR, each centred on the side line's level at the far side, that
// meet in the point at (32, 72). ArcR is chosen so the arcs leave the sides
// tangentially (no corner where the straight side becomes the curve).
const (
	GridW   = 64.0
	GridH   = 72.0
	Outline = 1.0  // the ink outline, drawn inside the grid
	SideY   = 36.0 // where the straight sides become the arcs
	PlaceSz = 24.0 // a charge place is a 24-unit square at 64 px
)

// ArcR is the radius that makes an arc from (0, SideY) tangent to the left
// side reach (32, GridH): (32-R)² + (GridH-SideY)² = R².
var ArcR = (32*32 + (GridH-SideY)*(GridH-SideY)) / 64

// Place is one of the five charge places, in place order TL TR C BL BR.
type Place struct {
	Name string  // tl, tr, c, bl, br
	X, Y float64 // top-left corner of the 24-unit square
}

// Places lays the five squares out as the five face of a die. The centre
// place is centred on (32, 29), the fess point; the corners sit 18 across and
// 15 up, or 16 across and 17 down, from it, chosen (scripts/heraldry-proto
// README, "Geometry") so a round charge clears its neighbours by ≥1.9 units
// and the outline by ≥2 units. The squares themselves overlap at their inner
// corners; charges are clipped to the field, so square artwork can never
// cross the outline.
var Places = []Place{
	{"tl", 2, 2},
	{"tr", 38, 2},
	{"c", 20, 17},
	{"bl", 4, 34},
	{"br", 36, 34},
}

// FessX, FessY is the centre of the centre place.
const FessX, FessY = 32.0, 29.0

// pather receives a shield outline. The raster side (vector.Rasterizer) and
// the SVG writer both implement it, so the two can never drift apart.
type pather interface {
	MoveTo(x, y float32)
	LineTo(x, y float32)
	CubeTo(x1, y1, x2, y2, x, y float32)
	ClosePath()
}

// tracePath traces the shield inset by `in` design units (0 is the outer
// edge, Outline is the field's edge), scaled by s and offset by (ox, oy).
// Insetting keeps the arc centres and shrinks the radius, which is an exact
// parallel offset of each arc.
func tracePath(p pather, in, s, ox, oy float64) {
	pt := func(x, y float64) (float32, float32) { return float32(ox + x*s), float32(oy + y*s) }
	r := ArcR - in
	tipY := SideY + math.Sqrt(r*r-(32-ArcR)*(32-ArcR))
	p.MoveTo(pt(in, in))
	p.LineTo(pt(GridW-in, in))
	p.LineTo(pt(GridW-in, SideY))
	arcTo(p, pt, GridW-ArcR, SideY, r, 0, math.Atan2(tipY-SideY, 32-(GridW-ArcR)))
	arcTo(p, pt, ArcR, SideY, r, math.Atan2(tipY-SideY, 32-ArcR), math.Pi)
	p.ClosePath()
}

// arcTo appends a circular arc (centre cx, cy; radius r; from angle a0 to a1,
// y down) as one cubic Bézier, accurate to ~1e-4·r for the ≤90° arcs here.
func arcTo(p pather, pt func(x, y float64) (float32, float32), cx, cy, r, a0, a1 float64) {
	k := 4.0 / 3.0 * math.Tan((a1-a0)/4) * r
	x0, y0 := cx+r*math.Cos(a0), cy+r*math.Sin(a0)
	x3, y3 := cx+r*math.Cos(a1), cy+r*math.Sin(a1)
	x1, y1 := x0-k*math.Sin(a0), y0+k*math.Cos(a0)
	x2, y2 := x3+k*math.Sin(a1), y3-k*math.Cos(a1)
	ax, ay := pt(x1, y1)
	bx, by := pt(x2, y2)
	cx3, cy3 := pt(x3, y3)
	p.CubeTo(ax, ay, bx, by, cx3, cy3)
}

// svgPath renders a traced path as an SVG path `d`.
type svgPath struct{ b strings.Builder }

func (s *svgPath) MoveTo(x, y float32) { fmt.Fprintf(&s.b, "M%s %s", num(x), num(y)) }
func (s *svgPath) LineTo(x, y float32) { fmt.Fprintf(&s.b, "L%s %s", num(x), num(y)) }
func (s *svgPath) CubeTo(x1, y1, x2, y2, x, y float32) {
	fmt.Fprintf(&s.b, "C%s %s %s %s %s %s", num(x1), num(y1), num(x2), num(y2), num(x), num(y))
}
func (s *svgPath) ClosePath() { s.b.WriteString("Z") }

func num(v float32) string {
	s := fmt.Sprintf("%.3f", v)
	s = strings.TrimRight(strings.TrimRight(s, "0"), ".")
	if s == "-0" {
		return "0"
	}
	return s
}

func pathD(in float64) string {
	var p svgPath
	tracePath(&p, in, 1, 0, 0)
	return p.b.String()
}

// Colours for the generated SVG: day ink and the azure sample field. A
// surface restyles them through the two CSS custom properties.
const (
	svgInk   = "#33261b"
	svgField = "#4c7ae0"
)

// ShieldSVG is the drawing: outline, field, and the five places as a clip
// group a renderer fills (empty places show the field).
func ShieldSVG() string {
	var b strings.Builder
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %g %g" width="%g" height="%g">
<!-- The standard heraldry shield (spec §6.2), 64×72 design units. Generated by
     scripts/heraldry-proto (go run . svg); edit shield.go, not this file. -->
<defs>
  <clipPath id="field"><path d="%s"/></clipPath>
</defs>
<path id="outline" d="%s" fill="var(--heraldry-ink, %s)"/>
<path id="field-cloth" d="%s" fill="var(--heraldry-field, %s)"/>
<g id="places" clip-path="url(#field)" fill="none">
`, GridW, GridH, GridW, GridH, pathD(Outline), pathD(0), svgInk, pathD(Outline), svgField)
	for _, pl := range Places {
		fmt.Fprintf(&b, "  <rect id=\"place-%s\" x=\"%g\" y=\"%g\" width=\"%g\" height=\"%g\"/>\n", pl.Name, pl.X, pl.Y, PlaceSz, PlaceSz)
	}
	b.WriteString("</g>\n</svg>\n")
	return b.String()
}

// ShieldGridSVG is the same drawing on its design grid, for people: a 4-unit
// grid over the shield, the places outlined and named, the fess point, the
// side/arc junction and the arc centres. Drawn at 8 px per unit.
func ShieldGridSVG() string {
	const u = 8.0
	const pad, foot = 40.0, 64.0
	var b strings.Builder
	w, h := GridW*u+2*pad, GridH*u+2*pad+foot
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %g %g" width="%g" height="%g" font-family="sans-serif" font-size="12">
<!-- The standard heraldry shield on its 64×72 design grid, 8 px per unit.
     Generated by scripts/heraldry-proto (go run . svg); edit shield.go. -->
<rect width="100%%" height="100%%" fill="#fbf6e4"/>
<g transform="translate(%g %g)">
`, w, h, w, h, pad, pad)
	fmt.Fprintf(&b, "  <g transform=\"scale(%g)\">\n    <path d=\"%s\" fill=\"%s\"/>\n    <path d=\"%s\" fill=\"%s\"/>\n  </g>\n",
		u, pathD(0), svgInk, pathD(Outline), svgField)
	grid := func(x1, y1, x2, y2 float64, major bool) {
		sw, op := "0.5", "0.45"
		if major {
			sw, op = "1", "0.7"
		}
		fmt.Fprintf(&b, "  <line x1=\"%g\" y1=\"%g\" x2=\"%g\" y2=\"%g\" stroke=\"#9a8f78\" stroke-opacity=\"%s\" stroke-width=\"%s\"/>\n", x1, y1, x2, y2, op, sw)
	}
	for x := 0.0; x <= GridW; x += 4 {
		grid(x*u, 0, x*u, GridH*u, int(x)%16 == 0)
	}
	for y := 0.0; y <= GridH; y += 4 {
		grid(0, y*u, GridW*u, y*u, int(y)%16 == 0)
	}
	for _, pl := range Places {
		fmt.Fprintf(&b, "  <rect x=\"%g\" y=\"%g\" width=\"%g\" height=\"%g\" fill=\"#fffaf0\" fill-opacity=\"0.2\" stroke=\"#fffaf0\" stroke-width=\"2\" stroke-dasharray=\"6 4\"/>\n",
			pl.X*u, pl.Y*u, PlaceSz*u, PlaceSz*u)
	}
	for _, pl := range Places {
		// Labels sit in a corner of their square that no other square covers.
		// The bottom pair drops below the red side/arc line.
		x, y, anchor := pl.X*u+8, pl.Y*u+18, "start"
		if pl.Name == "bl" || pl.Name == "br" {
			y = pl.Y*u + 40
		}
		if pl.Name == "br" {
			x, anchor = (pl.X+PlaceSz)*u-8, "end"
		}
		fmt.Fprintf(&b, "  <text x=\"%g\" y=\"%g\" fill=\"#fffaf0\" font-weight=\"bold\" text-anchor=\"%s\">%s (%g,%g)</text>\n", x, y, anchor, pl.Name, pl.X, pl.Y)
	}
	fmt.Fprintf(&b, "  <circle cx=\"%g\" cy=\"%g\" r=\"5\" fill=\"#d94a3a\"/>\n  <text x=\"%g\" y=\"%g\" fill=\"#fffaf0\" text-anchor=\"middle\">fess point (%g,%g)</text>\n",
		FessX*u, FessY*u, FessX*u, FessY*u+22, FessX, FessY)
	for _, cx := range []float64{ArcR, GridW - ArcR} {
		fmt.Fprintf(&b, "  <circle cx=\"%g\" cy=\"%g\" r=\"4\" fill=\"none\" stroke=\"#d94a3a\" stroke-width=\"2\"/>\n", cx*u, SideY*u)
	}
	fmt.Fprintf(&b, "  <line x1=\"-12\" y1=\"%g\" x2=\"%g\" y2=\"%g\" stroke=\"#d94a3a\" stroke-dasharray=\"4 4\"/>\n", SideY*u, GridW*u+12, SideY*u)
	fmt.Fprintf(&b, "  <text x=\"0\" y=\"-14\" fill=\"#33261b\">64 × 72 units · outline %g unit inside the grid · places %g units · grid lines every 4</text>\n", Outline, PlaceSz)
	foot0 := GridH*u + 24
	fmt.Fprintf(&b, "  <text x=\"0\" y=\"%g\" fill=\"#9a2c2c\">red: sides end at y=%g; arcs of radius %g centred ◦ at (%g,%g) and (%g,%g)</text>\n",
		foot0, SideY, ArcR, ArcR, SideY, GridW-ArcR, SideY)
	fmt.Fprintf(&b, "  <text x=\"0\" y=\"%g\" fill=\"#33261b\">places are clipped to the field, so a charge never crosses the outline; the centre is drawn last</text>\n", foot0+20)
	b.WriteString("</g>\n</svg>\n")
	return b.String()
}
