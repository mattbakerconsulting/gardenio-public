#!/usr/bin/env bash
# gen-drc-job.sh — regenerate the self-contained one-apply discriminating-check Job.
#
# The discriminating restore check (discriminating-restore-check.sh, bug
# ka-0000000357 req-1) must run inside a PRIVILEGED hostPath/hostPID pod on the
# prod dir-medium gVisor node — no gardenio agent SA can create such a pod or exec
# on a node, so an operator with a prod kubectl context drives it. To make that a
# genuine ONE-APPLY operation (no `kubectl cp` of a file from an unmerged branch,
# no manual probe-pod + exec + delete dance), we ship the script EMBEDDED in a
# self-contained ConfigMap+Job manifest:
#
#     scripts/gvisor/discriminating-check-job.yaml
#
# That manifest is GENERATED from discriminating-restore-check.sh by this script so
# the embedded copy can never silently drift from the source of truth. Regenerate
# after editing the .sh:
#
#     scripts/gvisor/gen-drc-job.sh
#
# (and commit both). drift-check.sh / CI can re-run this and `git diff --exit-code`.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
repo_root="$(cd "$here/../.." && pwd)"
src="$repo_root/scripts/gvisor/discriminating-restore-check.sh"
out="$repo_root/scripts/gvisor/discriminating-check-job.yaml"

[ -f "$src" ] || { echo "source script missing: $src" >&2; exit 1; }

# Indent the script by 4 spaces for the ConfigMap block scalar; keep blank lines
# truly empty (no trailing whitespace) so yaml/whitespace lint stays clean.
indented_script="$(awk '{ if (length($0)) print "    " $0; else print "" }' "$src")"

cat > "$out" <<EOF
# discriminating-check-job.yaml — GENERATED by scripts/gvisor/gen-drc-job.sh. DO NOT EDIT.
#   source of truth: scripts/gvisor/discriminating-restore-check.sh
#   regenerate:      scripts/gvisor/gen-drc-job.sh   (then commit both)
#
# THE ONE-APPLY zero-canary on-node discriminating restore check (bug ka-0000000357
# req-1). Settles — at ZERO canary cost, READ-ONLY w.r.t. prod — whether the merged
# dir-medium thaw fix (MRs !4910 + !4914) is SAFE or would mask real workspace loss,
# by replaying \`runsc --overlay2=root:dir restore\` of the already-persisted FAILING
# freeze bundle into a SCRATCH cid against COPIES under /var/tmp.
#
# WHY A JOB, NOT THE manual probe-pod + cp + exec dance: the script lives in a
# ConfigMap mounted in the CONTAINER fs, but the check runs after \`chroot /host\`
# (the node root), where that mount is invisible — so the Job copies the script to a
# host path FIRST, then chroots and runs it. That collapses the 5-step runbook to:
#
#     kubectl apply -f scripts/gvisor/discriminating-check-job.yaml
#     kubectl -n gvisor-poc logs -f job/gvisor-discriminating-check   # -> RESULT=PASS|FAIL
#
# Requires a prod kubectl context (america-e2e-eks, acct 234567890123). The pk8
# canary (ka-0000005316) froze agent "gardenio-uuae" on node ip-10-30-136-242; override
# via the AGENT env below if that ~5-day-old bundle was reaped (then re-drive ONE
# freeze on a fresh gvisor-poc agent to regenerate it — still zero thaw, zero canary).
#
# SAFETY: restores into a scratch cid against copies; never mutates the live
# checkpoint image, never deletes a pod, never reads or flips gvisor.freezeThaw.
# backoffLimit:0 (no retry of a privileged op); ttlSecondsAfterFinished self-cleans.
# Manual cleanup if needed: kubectl -n gvisor-poc delete job gvisor-discriminating-check
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: gvisor-drc-script
  namespace: gvisor-poc
  labels: {app: gvisor-discriminating-check, bug: ka-0000000357}
data:
  discriminating-restore-check.sh: |
$indented_script
---
apiVersion: batch/v1
kind: Job
metadata:
  name: gvisor-discriminating-check
  namespace: gvisor-poc
  labels: {app: gvisor-discriminating-check, bug: ka-0000000357}
spec:
  backoffLimit: 0                 # privileged restore op — never retry on failure
  ttlSecondsAfterFinished: 1800   # self-clean 30m after completion
  template:
    metadata:
      labels: {app: gvisor-discriminating-check}
    spec:
      restartPolicy: Never
      nodeSelector: {gvisor: enabled}
      tolerations:
      - {key: gvisor, operator: Equal, value: enabled, effect: NoSchedule}
      hostPID: true
      hostNetwork: true
      containers:
      - name: drc
        image: public.ecr.aws/docker/library/ubuntu:22.04
        securityContext: {privileged: true}
        # AGENT selects the persisted failing bundle to restore. Override with:
        #   kubectl -n gvisor-poc set env job/gvisor-discriminating-check AGENT=<name>
        # before the pod starts, or edit this value and re-apply.
        env:
        - {name: AGENT, value: "gardenio-uuae"}
        command: ["/bin/bash", "-c"]
        args:
        - |
          set -uo pipefail
          # The ConfigMap script is mounted in THIS container at /scripts; copy it onto
          # the node (/host) so it survives the chroot into the node root, then run it
          # there against the node's own runsc + /var/lib/gardenio bundle/overlay.
          install -m 0755 /scripts/discriminating-restore-check.sh /host/var/tmp/discriminating-restore-check.sh
          chroot /host /bin/bash -c "AGENT='\${AGENT}' /bin/bash /var/tmp/discriminating-restore-check.sh"
          rc=\$?
          echo "DRC_EXIT=\$rc"
          rm -f /host/var/tmp/discriminating-restore-check.sh 2>/dev/null || true
          exit \$rc
        volumeMounts:
        - {name: script, mountPath: /scripts}
        - {name: host, mountPath: /host}
        - {name: run, mountPath: /run}
      volumes:
      - name: script
        configMap: {name: gvisor-drc-script, defaultMode: 0755}
      - {name: host, hostPath: {path: /}}
      - {name: run, hostPath: {path: /run}}
EOF

echo "wrote $out ($(wc -l < "$out") lines, script embedded from $src)"
