#!/usr/bin/env bash
# reachability_test.sh — self-test for coverage-by-package.sh,
# summarize.sh, code-size.sh and, when go and deadcode are on PATH,
# deadcode.sh against a three-file fixture module.

set -euo pipefail
export LC_ALL=C

HERE=$(cd "$(dirname "$0")" && pwd)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
FAIL=0

check() { # check <name> <want> <got>
  if [[ "$2" == "$3" ]]; then
    echo "PASS $1"
  else
    echo "FAIL $1"
    echo "  want: $2"
    echo "  got:  $3"
    FAIL=1
  fi
}

# Two test binaries' worth of profile: m/a's block 1 appears twice (once
# unhit, once hit), so it must count once and as covered.
cat >"$TMP/p.out" <<'EOF'
mode: atomic
m/a/x.go:1.1,2.2 3 0
m/a/x.go:3.1,4.2 1 0
m/b/y.go:1.1,2.2 4 0
m/a/x.go:1.1,2.2 3 5
m/b/y.go:5.1,6.2 4 2
EOF
"$HERE/coverage-by-package.sh" "$TMP/p.out" >"$TMP/cov.tsv"

check "least covered first" "m/b	8	4	50.0" "$(sed -n 1p "$TMP/cov.tsv")"
check "dedupe keeps the hit" "m/a	4	3	75.0" "$(sed -n 2p "$TMP/cov.tsv")"
check "total row last" "(total)	12	7	58.3" "$(tail -n 1 "$TMP/cov.tsv")"

# A second profile sharing a block must not double its statements.
printf 'mode: atomic\nm/b/y.go:1.1,2.2 4 1\n' >"$TMP/q.out"
"$HERE/coverage-by-package.sh" "$TMP/p.out" "$TMP/q.out" >"$TMP/cov2.tsv"
check "profiles merge" "(total)	12	11	91.7" "$(tail -n 1 "$TMP/cov2.tsv")"

mkdir -p "$TMP/art/kbeads/dead" "$TMP/art/coverage"
printf 'cmd/kd\tshipped\t12\t3\n(all shipped)\tunion\t12\t3\n' >"$TMP/art/kbeads/summary-shipped.tsv"
printf 'cmd/x\tother\t4\t-\n' >"$TMP/art/kbeads/summary-other.tsv"
printf 'm/x\nm/y\n' >"$TMP/art/kbeads/packages-unshipped.txt"
: >"$TMP/art/kbeads/packages-unused.txt"
cp "$TMP/cov.tsv" "$TMP/art/coverage/kbeads.tsv"
"$HERE/summarize.sh" "$TMP/art" 1 >"$TMP/SUMMARY.md"

check "main row" "| \`cmd/kd\` | shipped | 12 | 3 |" "$(grep -F "\`cmd/kd\`" "$TMP/SUMMARY.md")"
check "row order" "shipped union other" "$(grep -o '| \(shipped\|union\|other\) |' "$TMP/SUMMARY.md" | tr -d '| ' | paste -sd ' ')"
check "unshipped count" "- imported by no shipped main: 2 (\`kbeads/packages-unshipped.txt\`)" "$(grep -F 'no shipped main' "$TMP/SUMMARY.md")"
check "coverage heading" "### kbeads: 58.3% of 12 statements" "$(grep '^### kbeads: [0-9]' "$TMP/SUMMARY.md")"
check "top-n bound" "1" "$(grep -c '^| `m/' "$TMP/SUMMARY.md")"

# code-size.sh against a fixture repo. long() is 104 lines and its raw
# string holds a column-0 "}" and a "//" that must not end it; gen.go is
# generated and left out. GOCYCLO points nowhere so the complexity columns
# read "-" whether or not this host has gocyclo.
R="$TMP/repo"
mkdir -p "$R/kbeads/x" "$R/coop/src" "$R/coop/tests" "$R/lands"
{
  # shellcheck disable=SC2016 # the backticks are Go source, not a command
  printf 'package x\n\nfunc long() string {\n\ts := `\n}\nhttps://x\n`\n'
  for _ in $(seq 1 97); do printf '\t_ = 1\n'; done
  printf '\treturn s\n}\n\nfunc (s *T[K]) short() { _ = "`" }\n'
} >"$R/kbeads/x/a.go"
printf 'package x\n\nfunc TestA() {\n}\n' >"$R/kbeads/x/a_test.go"
printf '// Code generated by hand. DO NOT EDIT.\n\npackage x\n' >"$R/kbeads/x/gen.go"
printf 'package l\n' >"$R/lands/l.go"
printf 'fn main() {}\n\n' >"$R/coop/src/main.rs"
printf 'mod t;\n' >"$R/coop/src/main_tests.rs"
printf 'mod u;\n' >"$R/coop/tests/u.rs"
git -C "$R" init -q && git -C "$R" add -A
GOCYCLO=/nonexistent/gocyclo "$HERE/code-size.sh" "$R" "$TMP/size" 2>/dev/null
check "size kbeads row" "kbeads	108	4	1	0	-	-	0	0" "$(grep '^kbeads' "$TMP/size/components.tsv")"
check "size coop row" "coop	0	0	0	0	-	-	2	2" "$(grep '^coop' "$TMP/size/components.tsv")"
check "size other row" "other	1	0	0	0	-	-	0	0" "$(grep '^other' "$TMP/size/components.tsv")"
check "size total row" "(total)	109	4	1	0	-	-	2	2" "$(grep '^(total)' "$TMP/size/components.tsv")"
check "long func" "kbeads	kbeads/x/a.go:3	long	104" "$(cat "$TMP/size/long-funcs.tsv")"
check "size packages" "kbeads/x 108 4|lands 1 0" "$(tr '\t' ' ' <"$TMP/size/packages.tsv" | paste -sd '|')"
mkdir -p "$TMP/art/size"
cp "$TMP/size/components.tsv" "$TMP/art/size/"
"$HERE/summarize.sh" "$TMP/art" 1 >"$TMP/SUMMARY2.md"
# shellcheck disable=SC2016 # literal Markdown backticks
check "size summary row" "| \`kbeads\` | 108 | 4 | 1 | 0 | - | - | 0 | 0 |" "$(grep -F '| `kbeads` |' "$TMP/SUMMARY2.md")"

if command -v go >/dev/null && command -v "${DEADCODE:-deadcode}" >/dev/null; then
  M="$TMP/mod"
  mkdir -p "$M/cmd/app" "$M/cmd/tool" "$M/lib" "$M/orphan"
  printf 'module example.com/m\n\ngo 1.22\n' >"$M/go.mod"
  printf 'package main\n\nimport "example.com/m/lib"\n\nfunc main() { lib.Used() }\n' >"$M/cmd/app/main.go"
  printf 'package main\n\nfunc main() {}\n' >"$M/cmd/tool/main.go"
  printf 'package lib\n\nfunc Used() {}\n\nfunc TestOnly() {}\n\nfunc Dead() {}\n' >"$M/lib/lib.go"
  printf 'package lib\n\nimport "testing"\n\nfunc TestX(t *testing.T) { TestOnly() }\n' >"$M/lib/lib_test.go"
  printf 'package orphan\n\nfunc F() {}\n' >"$M/orphan/o.go"
  # A second workspace module, as in the repo's go.work: `go list -m` there
  # names both, which once left deadcode.sh with no mains at all.
  mkdir -p "$TMP/other"
  printf 'module example.com/other\n\ngo 1.22\n' >"$TMP/other/go.mod"
  printf 'go 1.22\n\nuse (\n\t./mod\n\t./other\n)\n' >"$TMP/go.work"
  (cd "$TMP" && GOWORK="$TMP/go.work" "$HERE/deadcode.sh" mod "$TMP/dc" shipped cmd/app >/dev/null)
  (cd "$TMP" && GOWORK="$TMP/go.work" "$HERE/deadcode.sh" mod "$TMP/dc" other cmd/app >/dev/null)
  D="$TMP/dc/mod"
  check "dead from app" "Dead TestOnly" "$(cut -f2 "$D/dead/cmd-app.tsv" | tr '\n' ' ' | sed 's/ $//')"
  check "test-only" "TestOnly" "$(cut -f2 "$D/test-only/cmd-app.tsv")"
  check "unshipped package" "example.com/m/orphan" "$(cat "$D/packages-unshipped.txt")"
  check "summary rows" "(all shipped) union 2 1|cmd/app shipped 2 1|cmd/tool other 0 -" "$(cat "$D"/summary-*.tsv | sort | tr '\t' ' ' | paste -sd '|')"
else
  echo "SKIP deadcode.sh fixture (needs go and deadcode on PATH)"
fi

exit "$FAIL"
