#!/usr/bin/env bash
# line-budget_test.sh — self-test for line-budget.sh against a fixture repo,
# through the real code-size.sh.

set -euo pipefail
export LC_ALL=C

HERE=$(cd "$(dirname "$0")" && pwd)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
FAIL=0

check() { # check <name> <want> <got>
  if [[ "$2" == "$3" ]]; then
    echo "PASS $1"
  else
    echo "FAIL $1"
    echo "  want: $2"
    echo "  got:  $3"
    FAIL=1
  fi
}

# lines <file> <n> [package]: a Go file of exactly n lines.
lines() {
  mkdir -p "$(dirname "$1")"
  { printf 'package %s\n' "${3:-p}"; for _ in $(seq 2 "$2"); do printf '// x\n'; done; } >"$1"
}

R="$TMP/repo"
mkdir -p "$R/scripts/ratchets"
lines "$R/small/a.go" 100
lines "$R/small/a_test.go" 40
lines "$R/big/b.go" 20000
printf '// Code generated by hand. DO NOT EDIT.\npackage big\n' >"$R/big/gen.go"
git -C "$R" init -q
add() { git -C "$R" add -A; }
add
B="$R/scripts/ratchets/line-budget.tsv"
LB="$HERE/line-budget.sh"

check "usage" "2" "$(set +e; "$LB" bogus >/dev/null 2>&1; echo $?)"
check "check needs a budget file" "2" "$(set +e; "$LB" check "$B" >/dev/null 2>&1; echo $?)"

"$LB" update "$B" >/dev/null
# 100 -> 100+500; 40 -> 600 (500 floor, rounded up); 20000 -> 21000 (5%);
# 0 test lines -> the 500 floor. gen.go is generated and not counted.
check "update writes the rule" "big 21000 500|small 600 600" "$(grep -v '^#' "$B" | tr '\t' ' ' | paste -sd '|')"
check "within budget" "0" "$(set +e; "$LB" check "$B" >/dev/null; echo $?)"

lines "$R/big/b.go" 21001; add
out=$(set +e; "$LB" check "$B"; echo "rc=$?")
check "over budget fails" "rc=1" "$(tail -n 1 <<<"$out")"
check "over budget names the package" "  big  src  21001 > 21000" "$(grep '^  big' <<<"$out")"

"$LB" update "$B" >/dev/null
check "update never raises" "big 21000 500" "$(grep '^big' "$B" | tr '\t' ' ')"

lines "$R/big/b.go" 15000; add
"$LB" update "$B" >/dev/null
check "update lowers" "big 15800 500" "$(grep '^big' "$B" | tr '\t' ' ')"

lines "$R/fresh/f.go" 500 fresh; add
check "new package within 500 passes" "0" "$(set +e; "$LB" check "$B" >/dev/null; echo $?)"
lines "$R/fresh/f_test.go" 501 fresh; add
out=$(set +e; "$LB" check "$B"; echo "rc=$?")
check "new package past 500 fails" "rc=1" "$(tail -n 1 <<<"$out")"
check "new package is named" "  fresh  test  501 > 500 (new package, no row)" "$(grep '^  fresh' <<<"$out")"
"$LB" update "$B" >/dev/null
check "update adds the new package" "fresh 1000 1100" "$(grep '^fresh' "$B" | tr '\t' ' ')"

# Grants (gd-jMdrPDGpPw): line-budget.d/*.tsv rows add to a package's row, so
# concurrent PRs each add a file instead of editing the same row.
G="$R/scripts/ratchets/line-budget.d"
mkdir -p "$G"
lines "$R/big/b.go" 16000; add
check "over the row without a grant" "1" "$(set +e; "$LB" check "$B" >/dev/null; echo $?)"
printf '# why\nbig\t150\t0' >"$G/a.tsv"  # no trailing newline: the next file's row must still count
printf 'big\t100\t0\n' >"$G/b.tsv"
check "two grants add up" "0" "$(set +e; "$LB" check "$B" >/dev/null; echo $?)"
rm "$G/b.tsv"
out=$(set +e; "$LB" check "$B"; echo "rc=$?")
check "one grant short fails" "  big  src  16000 > 15950" "$(grep '^  big' <<<"$out")"
check "the message points at a grant file" "1" "$(grep -c 'line-budget.d/<bead-id>.tsv' <<<"$out")"
printf 'big\t100\t0\n' >"$G/b.tsv"
printf 'fresh\t0\t10\n' >"$G/c.tsv"
lines "$R/fresh/f_test.go" 1101 fresh; add
check "a grant for a third package" "0" "$(set +e; "$LB" check "$B" >/dev/null; echo $?)"
"$LB" update "$B" >/dev/null
check "update folds grants into the rows" "big 16050 500|fresh 1000 1110" "$(grep -E '^(big|fresh)' "$B" | tr '\t' ' ' | paste -sd '|')"
check "update deletes the grants it folded" "" "$(ls "$G")"
check "folded budget still passes" "0" "$(set +e; "$LB" check "$B" >/dev/null; echo $?)"

git -C "$R" rm -rqf small
"$LB" update "$B" >/dev/null
check "update drops a gone package" "" "$(grep '^small' "$B" || true)"
check "header kept" "# package	src	test" "$(grep '^# package' "$B")"

exit "$FAIL"
