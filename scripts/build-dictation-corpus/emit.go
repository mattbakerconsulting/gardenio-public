package main

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// artifact names — the tool writes exactly these three files into outDir.
const (
	artifactGlossary = "glossary.json"
	artifactPhrases  = "phrases.yaml"
	artifactCorpus   = "corpus.txt"
)

// writeGlossary serializes the top-N glossary terms as a JSON array of
// strings, suitable for direct use as SFSpeechRecognitionRequest.contextualStrings.
func writeGlossary(outDir string, terms []string) error {
	path := filepath.Join(outDir, artifactGlossary)
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	enc := json.NewEncoder(f)
	enc.SetIndent("", "  ")
	if terms == nil {
		terms = []string{}
	}
	return enc.Encode(terms)
}

// phrasesDoc is the on-disk shape of phrases.yaml. It is intentionally a
// flat YAML that either SpeechModelBuilder or a small bespoke build step
// can consume. The identifier/locale/version fields are the SpeechModel
// bake inputs; `custom_words` feeds the vocabulary bias; `phrases` feeds
// the PhraseCount/TemplateCount builder on iOS 17+/macOS 14+.
type phrasesDoc struct {
	Locale      string
	Identifier  string
	Version     int
	CustomWords []string
	Phrases     []string
}

// writePhrases emits a minimal YAML document. We format it by hand to
// avoid pulling in a YAML dependency for the scripts/ module: the shape
// is small and stable, and we control the keys.
func writePhrases(outDir string, doc phrasesDoc) error {
	path := filepath.Join(outDir, artifactPhrases)
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return writePhrasesTo(f, doc)
}

func writePhrasesTo(w io.Writer, doc phrasesDoc) error {
	if doc.Locale == "" {
		doc.Locale = "en-US"
	}
	if doc.Identifier == "" {
		doc.Identifier = "ai.acme.gardenio.dictation"
	}
	if doc.Version == 0 {
		doc.Version = 1
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by scripts/build-dictation-corpus — do not edit by hand\n")
	fmt.Fprintf(&b, "locale: %s\n", yamlString(doc.Locale))
	fmt.Fprintf(&b, "identifier: %s\n", yamlString(doc.Identifier))
	fmt.Fprintf(&b, "version: %d\n", doc.Version)
	fmt.Fprintf(&b, "custom_words:\n")
	for _, w := range doc.CustomWords {
		fmt.Fprintf(&b, "  - %s\n", yamlString(w))
	}
	fmt.Fprintf(&b, "phrases:\n")
	for _, p := range doc.Phrases {
		fmt.Fprintf(&b, "  - %s\n", yamlString(p))
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// yamlString returns a safely-quoted YAML scalar. We always emit
// double-quoted strings with JSON-style escaping so the output is
// unambiguous for any ASCII-printable input (including colons, hashes,
// leading dashes, and embedded quotes).
func yamlString(s string) string {
	// JSON encoding is a strict subset of YAML double-quoted scalars for
	// ASCII text: it escapes control chars, quotes, and backslashes, and
	// always produces a valid YAML value. json.Marshal never fails on a
	// string input, so we can drop the error.
	buf, _ := json.Marshal(s)
	return string(buf)
}

// writeCorpus writes one clean text chunk per line to corpus.txt.
// Empty chunks are skipped. A trailing newline is emitted.
func writeCorpus(outDir string, chunks []string) error {
	path := filepath.Join(outDir, artifactCorpus)
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	for _, c := range chunks {
		c = strings.TrimSpace(c)
		if c == "" {
			continue
		}
		// Normalize internal newlines to spaces so each bead chunk is one
		// long line — friendlier for tools that diff the corpus by line.
		c = strings.ReplaceAll(c, "\n", " ")
		if _, err := fmt.Fprintln(f, c); err != nil {
			return err
		}
	}
	return nil
}
