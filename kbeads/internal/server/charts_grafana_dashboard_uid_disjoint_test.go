package server

import (
	"encoding/json"
	"os"
	"path/filepath"
	"sort"
	"testing"
)

// This is the durable guard for ka-0000002712: it stops a dashboard uid in the
// kbeads catalog (dashboardCatalog(), the CATALOG-GENERATED / bridge-provisioned
// boards) from COLLIDING with a uid that a chart-shipped dashboard JSON already
// owns (gardenio/helm/gardenio/dashboards/*.json — the chart-bundle-baked boards
// the grafana-bridge backfills as type=dashboard beads).
//
// ── The failure mode it guards ───────────────────────────────────────────────
// The two provisioning paths are DISJOINT by contract (charts_grafana_dashboard.go
// header): every uid in dashboardCatalog() is NOT chart-bundle-owned, and the
// bridge treats a chart-bundle uid as chart-owned (ChartOwnsDashboard=true). If
// one uid appears on BOTH sides, they fight over a single Grafana dashboard:
//
//   - `kd admin gen-dashboards` (re)writes the catalog board's model doc for
//     that uid, OVERWRITING the chart board's backfilled model with the catalog
//     panels; and
//   - GrafanaSync, seeing the uid is chart-owned, calls RemoveOwn on the bridge
//     shadow.
//
// So the operator's trace-search board and the catalog RED board silently
// clobber each other. This is exactly what merge fef109705 introduced: the W2b
// RED board claimed `gardenio-perf-traces`, already owned by
// helm/gardenio/dashboards/perf-traces.json. The fix renamed the catalog board to
// `gardenio-perf-traces-red`; this guard keeps the two id-spaces disjoint forever.
//
// ── Where it runs ────────────────────────────────────────────────────────────
// The chart JSONs live in a sibling path (gardenio/helm/) reached by relative
// path. On a partial checkout without that tree the glob matches nothing and the
// test SKIPS (mirroring config_seed_shadow_test.go / config_driftguard_test.go).
// CI checks out the whole monorepo, so the guard always runs there.
// TestDashboardUIDDisjoint_DetectsCollision is
// the anti-vacuity companion that exercises the detection logic with synthetic
// data, so the guard is never silently green because the intersection helper
// broke.

// chartBundleDashboardsGlob globs every chart-shipped dashboard JSON from the
// package dir (kbeads/internal/server). These are the boards baked into the Helm
// chart bundle ConfigMap and backfilled by the grafana-bridge.
const chartBundleDashboardsGlob = "../../../gardenio/helm/gardenio/dashboards/*.json"

// chartBundleUID is the top-level "uid" of a chart-shipped dashboard JSON,
// extracted exactly as the grafana-bridge does when it backfills the file
// (bridge.ParseDashboardMeta / the backfill dashboard_uid): a plain unmarshal of
// the TOP-LEVEL uid, which ignores nested datasource `uid` template vars.
type chartBundleUID struct {
	UID string `json:"uid"`
}

// chartBundleDashboardUIDs globs every chart-shipped dashboard JSON and returns
// the non-empty top-level uids it declares, plus the number of files scanned.
// Skips the test when the sibling chart tree is not checked out.
func chartBundleDashboardUIDs(t *testing.T) (uids []string, fileCount int) {
	t.Helper()
	absGlob := mustAbs(t, chartBundleDashboardsGlob)
	files, err := filepath.Glob(absGlob)
	if err != nil {
		t.Fatalf("glob %s: %v", absGlob, err)
	}
	if len(files) == 0 {
		t.Skipf("no chart dashboards matched %s; uid-disjoint guard "+
			"runs where the gardenio sibling tree is present", chartBundleDashboardsGlob)
	}
	sort.Strings(files)
	for _, path := range files {
		data, rerr := os.ReadFile(path)
		if rerr != nil {
			t.Fatalf("read %s: %v", path, rerr)
		}
		var meta chartBundleUID
		if err := json.Unmarshal(data, &meta); err != nil {
			t.Fatalf("chart dashboard %s is not valid JSON: %v", filepath.Base(path), err)
		}
		// An empty top-level uid can't collide and isn't a real dashboard
		// identity (Grafana would assign one on import); skip it.
		if meta.UID != "" {
			uids = append(uids, meta.UID)
		}
	}
	return uids, len(files)
}

// intersectSorted returns the sorted set intersection of two string slices,
// deduplicated. Pure — the detection primitive the disjointness guard asserts is
// empty and the anti-vacuity test exercises directly.
func intersectSorted(a, b []string) []string {
	set := make(map[string]struct{}, len(a))
	for _, s := range a {
		set[s] = struct{}{}
	}
	seen := make(map[string]struct{})
	var out []string
	for _, s := range b {
		if _, ok := set[s]; !ok {
			continue
		}
		if _, dup := seen[s]; dup {
			continue
		}
		seen[s] = struct{}{}
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

// TestDashboardUIDs_DisjointFromChartBundle is the guard: no uid generated by the
// kbeads dashboard catalog may also be owned by a chart-shipped dashboard JSON.
// A collision means two provisioning paths fight over one Grafana dashboard
// (ka-0000002712).
func TestDashboardUIDs_DisjointFromChartBundle(t *testing.T) {
	catalogUIDs := DashboardUIDs()
	if len(catalogUIDs) == 0 {
		t.Fatal("DashboardUIDs() is empty — the catalog declares no dashboards")
	}

	chartUIDs, fileCount := chartBundleDashboardUIDs(t)
	// Anti-vacuity: the sibling tree is present (we did not skip), so we must
	// have parsed real uids out of it. A glob that matched files but yielded no
	// uids means the extraction regressed and the guard would pass blindly.
	if len(chartUIDs) == 0 {
		t.Fatalf("scanned %d chart dashboard file(s) but extracted zero uids — "+
			"uid extraction regressed; the disjointness guard would be vacuous", fileCount)
	}

	if collisions := intersectSorted(catalogUIDs, chartUIDs); len(collisions) > 0 {
		t.Errorf("dashboard uid collision(s) between the kbeads catalog "+
			"(dashboardCatalog) and chart-shipped JSON (gardenio/helm/gardenio/dashboards): %v.\n"+
			"Every catalog uid must be NOT chart-bundle-owned (charts_grafana_dashboard.go header). "+
			"Rename the catalog board's UID (e.g. add a `-red`/`-candidate` suffix) so the two "+
			"provisioning paths never overwrite each other (ka-0000002712).", collisions)
	}
}

// TestDashboardUIDDisjoint_DetectsCollision exercises the intersection primitive
// directly with synthetic sets — no file dependency, so it runs even on a
// partial checkout where the sibling chart tree is absent. It is the
// anti-vacuity companion to TestDashboardUIDs_DisjointFromChartBundle: the real
// guard passes because the id-spaces are disjoint today, so without this a broken
// detector (one that never reports an overlap) would look green forever.
func TestDashboardUIDDisjoint_DetectsCollision(t *testing.T) {
	tests := []struct {
		name string
		a    []string
		b    []string
		want []string
	}{
		{
			name: "disjoint sets have empty intersection",
			a:    []string{"gardenio-costs-candidate", "gardenio-perf-traces-red"},
			b:    []string{"gardenio-perf-traces", "gardenio-system-health"},
			want: nil,
		},
		{
			name: "the exact fef109705 collision is caught",
			a:    []string{"gardenio-costs-candidate", "gardenio-perf-traces"},
			b:    []string{"gardenio-perf-traces", "gardenio-system-health"},
			want: []string{"gardenio-perf-traces"},
		},
		{
			name: "multiple overlaps are all reported, sorted and deduped",
			a:    []string{"b", "a", "c"},
			b:    []string{"c", "a", "a"},
			want: []string{"a", "c"},
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := intersectSorted(tc.a, tc.b)
			if len(got) != len(tc.want) {
				t.Fatalf("intersectSorted(%v, %v) = %v, want %v", tc.a, tc.b, got, tc.want)
			}
			for i := range tc.want {
				if got[i] != tc.want[i] {
					t.Errorf("intersectSorted(%v, %v)[%d] = %q, want %q", tc.a, tc.b, i, got[i], tc.want[i])
				}
			}
		})
	}
}
